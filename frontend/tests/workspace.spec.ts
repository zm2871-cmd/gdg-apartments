import { expect, test } from '@playwright/test'

test('searches, opens a report, expands grade evidence, and filters the map', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Know the building before you sign the lease.' })).toBeVisible()
  const input = page.getByRole('combobox', { name: 'NYC address' })
  await input.fill('123 Example')
  await expect(page.getByRole('option', { name: /123 Example Street/ })).toBeVisible()
  await page.getByRole('button', { name: 'Search', exact: true }).click()
  await expect(page).toHaveURL(/\/search\?q=/)
  await page.getByRole('button', { name: /123 Example Street/ }).click()
  await expect(page.getByRole('heading', { name: '123 Example Street' })).toBeVisible()
  await page.getByRole('button', { name: /Grade B Repairs/ }).click()
  await expect(page.getByText('Maintenance violations', { exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Supporting records' })).toBeVisible()
  await page.getByRole('button', { name: 'Pests', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Noise complaint nearby', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Nearby pest record', exact: true }).click()
  await expect(page.getByText('Sample pest complaint on the adjacent block.')).toBeVisible()
  await page.getByRole('button', { name: 'Show more issues' }).click()
  await expect(page.getByText('Showing 5 of 5')).toBeVisible()
})

test('persists a saved building, compares it, replaces a selection, and removes it', async ({ page }) => {
  await page.goto('/building/example-street')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Saved', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Saved' }).click()
  await page.reload()
  await expect(page.getByRole('heading', { name: '123 Example Street' })).toBeVisible()
  await page.getByRole('button', { name: 'Add to compare' }).click()
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: /Compare/ }).click()
  const address = page.getByRole('combobox', { name: 'Address to compare' })
  await address.fill('48 Sample')
  await expect(page.getByRole('option', { name: /48 Sample Avenue/ })).toBeVisible()
  await address.press('ArrowDown')
  await address.press('Enter')
  await expect(page.getByRole('heading', { name: '48 Sample Avenue' })).toBeVisible()
  await expect(page.getByText('Missing comparable data: Bedbugs.')).toBeVisible()
  await page.getByRole('button', { name: 'Replace 48 Sample Avenue' }).click()
  await page.getByRole('combobox', { name: 'Replacement address' }).fill('76 Demo')
  await page.getByRole('option', { name: /76 Demo Place/ }).click()
  await expect(page.getByRole('heading', { name: '76 Demo Place' })).toBeVisible()
  await page.getByRole('button', { name: 'Remove 76 Demo Place' }).click()
  await expect(page.getByText('Add one more building to see a weighted comparison.')).toBeVisible()
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Saved' }).click()
  await page.getByRole('button', { name: 'Remove saved' }).click()
  await expect(page.getByRole('heading', { name: 'No saved properties yet' })).toBeVisible()
})

test('saves, restores, and resets rating preferences', async ({ page }) => {
  await page.goto('/compare')
  await page.getByRole('button', { name: 'Compare two sample buildings' }).click()
  await expect(page.getByText('Sample weighted score / 100')).toHaveCount(2)
  await page.getByText('Rating preferences', { exact: true }).click()
  await page.getByRole('radio', { name: 'Advanced', exact: true }).check()
  await page.getByRole('slider', { name: 'Complaint frequency' }).focus()
  await page.keyboard.press('Home')
  await page.getByRole('button', { name: 'Save preferences' }).click()
  await expect(page.getByText('Preferences saved and applied.')).toBeVisible()
  await page.getByRole('button', { name: 'Reset to defaults' }).click()
  await expect(page.getByRole('radio', { name: 'Default', exact: true })).toBeChecked()
  await page.getByRole('button', { name: 'Restore saved' }).click()
  await expect(page.getByRole('radio', { name: 'Advanced', exact: true })).toBeChecked()
  await expect(page.getByRole('slider', { name: 'Complaint frequency' })).toHaveValue('0')
  await page.getByRole('button', { name: 'Reset to defaults' }).click()
  await page.getByRole('button', { name: 'Save preferences' }).click()
  await page.reload()
  await page.getByText('Rating preferences', { exact: true }).click()
  await expect(page.getByRole('radio', { name: 'Default', exact: true })).toBeChecked()
})

test('shows missing information and handles mobile navigation without horizontal scrolling', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 })
  await page.goto('/building/demo-place')
  await expect(page.getByText('A summary is unavailable for this report.')).toBeVisible()
  await expect(page.getByRole('button', { name: /Grade unavailable Rats & pests/ })).toBeVisible()
  const grades = await page.getByRole('heading', { name: 'Building grades' }).boundingBox()
  const map = await page.getByRole('heading', { name: 'What’s nearby?' }).boundingBox()
  const recent = await page.getByRole('heading', { name: 'Recent issues' }).boundingBox()
  expect(grades!.y).toBeLessThan(map!.y)
  expect(map!.y).toBeLessThan(recent!.y)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(375)
  await page.getByRole('button', { name: 'Open navigation' }).click()
  await page.getByRole('link', { name: 'How it works', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'How it works' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Open navigation' })).toHaveAttribute('aria-expanded', 'false')
  await page.goto('/search?q=imaginary-address')
  await expect(page.getByRole('heading', { name: 'No matching addresses' })).toBeVisible()
})

test('aligns three building columns on desktop and preserves category labels on a narrow screen', async ({ page }) => {
  await page.goto('/compare')
  await page.getByRole('button', { name: 'Compare two sample buildings' }).click()
  await expect(page.getByRole('heading', { name: '48 Sample Avenue' })).toBeVisible()
  const address = page.getByRole('combobox', { name: 'Address to compare' })
  await address.fill('76 Demo')
  await page.getByRole('option', { name: /76 Demo Place/ }).click()
  await expect(page.getByRole('heading', { name: '76 Demo Place' })).toBeVisible()
  const cards = page.getByRole('article')
  await expect(cards).toHaveCount(3)
  const first = await cards.nth(0).boundingBox()
  const third = await cards.nth(2).boundingBox()
  expect(first!.y).toBe(third!.y)
  expect(first!.x).toBeLessThan(third!.x)
  await page.setViewportSize({ width: 320, height: 760 })
  const mobileFirst = await cards.nth(0).boundingBox()
  const mobileThird = await cards.nth(2).boundingBox()
  expect(mobileFirst!.x).toBe(mobileThird!.x)
  expect(mobileFirst!.y).toBeLessThan(mobileThird!.y)
  await expect(cards.nth(2).getByText('Heat & hot water', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(320)
})
